/**
 * ACT-R 工程参数（B3.1）—— **本仓唯一出处**。
 *
 * 真源：`docs/mana-v5-plan.md:351-370`（§5.1 工程参数建议 + 检索概率与延迟计算）。
 * 判据真源：`docs/mana-rollout-plan.md:516-517`（A2-1 / A2-2）。
 *
 * ⚠ **为什么单独成文件**：`册:820` C14「派生量唯一写者」要求同一条记忆**不得被两家乘过**。
 *   参数若散落在各函数默认值里，改一处不会改另一处 ⇒ 迟早出现"两个 d""两个 s"。
 *   本文件把 5 个工程参数 + 1 个派生量（`s`）**收在一处**，其余模块与测试**只许读、不许重写**。
 *
 * ⚠ **单位不一致是刻意的，且是最容易踩的坑**（本文件存在的第二个理由）：
 *   · `D` / `baseLevel` 的练习时间 `t_j` 单位是 **秒**（A2-1 锚点 `B{[1]}` 即"1 秒前访问过一次"）；
 *   · `HALF_LIFE_DAYS` / `decay` 的时间 `t` 单位是 **天**（A1-5 锚点 `decay(14)=0.5` 即"14 天后衰减一半"）。
 *   两者**不是同一个量**：前者是 ACT-R 基础激活的幂律衰减，后者是存储层的半衰期留存率。
 *   把它们相乘（`B × decay`）就是 C14 说的"同一条记忆被两家乘过" —— 本仓明令禁止，
 *   由 `tests/activation.test.mjs` 判据 ② 的"同形腿"机检（`baseLevel` 必须纯幂律、无额外指数因子）。
 */

/** ACT-R 衰减指数（方案 §5.1：默认 0.5）。**基础激活的幂律指数**，非半衰期。 */
export const D = 0.5

/** 检索阈值 τ（方案 §5.1：-2.0）。低于此值不返回。 */
export const TAU = -2.0

/** 噪声 σ（方案 §5.1：0.3）。生产检索随机性。 */
export const SIGMA = 0.3

/**
 * 逻辑分布尺度 `s = √3·σ/π`（方案 §5.1 行347-348）。
 *
 * ⚠ **派生量**：由 `SIGMA` 推出，**不得**再独立配置。
 *   A2-2 锚点 `s(σ=0.3)=0.165399` 正是本式；若误把 `σ=0.3` 当 `s` 直接代入，
 *   `P(A=τ+1)` 会算成 0.965555（≠ 判据的 0.997638，差 3.2e-2 ≫ 1e-6）。
 *   `tests/activation.test.mjs` 判据 ③ 含该反向对照。
 *
 * 同一尺度同时用于：① 检索概率的逻辑函数；② 噪声项 ε 的分布尺度 —— **一个 s，不是两个**（C14 收敛口径）。
 */
export const S_NOISE = (Math.sqrt(3) * SIGMA) / Math.PI

/** 时间尺度 F = 0.35s（方案 §5.1：ACT-R 默认检索时间因子）。 */
export const LATENCY_F = 0.35

/** 激活→延迟的缩放因子 f = 0.8（方案 §5.1）。 */
export const LATENCY_F_SCALE = 0.8

/**
 * 时间衰减半衰期 h = 14 天（A1-5 冻结锚点：`decay(14)=0.500000`）。
 *
 * ⚠ **本批只接这一套**（rollout:503③ 的收敛口径）：`d=0.5` / `h=14天` / `S`+Pavlik–Anderson
 *   三套公式必须收敛为一套。`S` 更新（Pavlik & Anderson）属 B4.2（`forgetting`），本包**不实现**；
 *   `d` 只作用于基础激活的幂律项（见上面 `D`）。本包内**只有 `decay` 一处**对时间做指数衰减。
 * ⛔ **不接 FSRS**（v10 §17.1 裁定不移植）：与已冻结的 `decay(14)=0.500000` 冲突。
 */
export const HALF_LIFE_DAYS = 14

/** 冻结参数快照（**只读**；服务面 `params` 即吐出本对象，供判据/其余模块读而非重写）。 */
export const ACTR_PARAMS = Object.freeze({
  /** 基础激活幂律指数 d */
  d: D,
  /** 检索阈值 τ */
  tau: TAU,
  /** 噪声 σ */
  sigma: SIGMA,
  /** 逻辑尺度 s = √3σ/π（派生量） */
  s: S_NOISE,
  /** 时间尺度 F（秒） */
  latencyF: LATENCY_F,
  /** 激活→延迟缩放因子 f */
  latencyFScale: LATENCY_F_SCALE,
  /** 时间衰减半衰期（天） */
  halfLifeDays: HALF_LIFE_DAYS,
})
